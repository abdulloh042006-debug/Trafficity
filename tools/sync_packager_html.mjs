#!/usr/bin/env node
/**
 * Keeps the pure logic embedded in Trafficity-Uzbekistan-Complete-Packager.html identical to tools/packager_core.mjs.
 *
 *   node tools/sync_packager_html.mjs           rewrite the embedded copy
 *   node tools/sync_packager_html.mjs --check   exit 1 when the HTML copy differs from the module (used by npm test / CI)
 *
 * The module has no imports; the only transformation is removing the `export ` keyword in front of declarations,
 * so the page runs the very code the tests exercise. The page contains no external scripts or stylesheets.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const CORE_PATH = join(ROOT, "tools", "packager_core.mjs");
export const HTML_PATH = join(ROOT, "Trafficity-Uzbekistan-Complete-Packager.html");
export const BEGIN = "<!-- CORE-SYNC:BEGIN (generated by tools/sync_packager_html.mjs - do not edit by hand) -->";
export const END = "<!-- CORE-SYNC:END -->";

/** Core module source as it must appear inside the page's classic <script>. */
export function coreForHtml(source) {
  if (/^\s*import\s/m.test(source)) throw new Error("packager_core.mjs must not contain import statements");
  if (source.includes("</script")) throw new Error("packager_core.mjs must not contain </script");
  return source.replace(/^export (async function|function|class|const|let) /gm, "$1 ").trimEnd();
}

export function embeddedCoreFromHtml(html) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error("CORE-SYNC markers not found in the HTML packager");
  const block = html.slice(a + BEGIN.length, b);
  const m = block.match(/<script id="packager-core">\n([\s\S]*?)\n<\/script>/);
  if (!m) throw new Error('<script id="packager-core"> not found between the CORE-SYNC markers');
  return m[1];
}

export function withCore(html, source) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error("CORE-SYNC markers not found in the HTML packager");
  return `${html.slice(0, a)}${BEGIN}\n<script id="packager-core">\n${coreForHtml(source)}\n</script>\n${html.slice(b)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const html = readFileSync(HTML_PATH, "utf8");
  const source = readFileSync(CORE_PATH, "utf8");
  if (process.argv.includes("--check")) {
    if (embeddedCoreFromHtml(html) !== coreForHtml(source)) {
      console.error("FAIL: the code embedded in the HTML packager differs from tools/packager_core.mjs (run: node tools/sync_packager_html.mjs)");
      process.exit(1);
    }
    console.log("OK: embedded core is identical to tools/packager_core.mjs");
  } else {
    writeFileSync(HTML_PATH, withCore(html, source));
    console.log("Updated the embedded core in", HTML_PATH);
  }
}
